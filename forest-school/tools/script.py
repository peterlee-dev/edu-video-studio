"""숲 학교 사계절 — 대본 (봄·여름·가을·겨울 4편)

줄 종류
  N(...)  내레이터(밝은 여성 목소리)      T(...)  곰취 선생님(다정한 할아버지 목소리)
  Q(...)  장면 끝 확인 문제: 문제 읽기 → 5초 카운트다운 → 정답 발표
  골든벨은 편 끝의 GB 목록 (같은 Q 모양, 번호가 붙어요)
화면
  bg='키'   이 줄부터 바뀌는 장면 그림 (img/gen/키.png, 다음 bg 까지 유지)
  ov=...    이 줄 동안 그림 위에 띄우는 것
     ('panel', '키', ['이름', ('이름', '짧은 설명'), ...])   생물 그림판 + 칸마다 이름표
     ('key', '낱말', '뜻')                                 핵심 낱말 카드
     ('chain', '키', ['새', '개구리', ...])               먹이 사슬(화살표)
     ('chart', 'trash')  ('anat', 'su_insect')  ('nodes', 'sp_pinetree')   이 영상 전용 그림
  tts='...' 화면 글자와 읽는 소리가 다를 때(숫자 등) 읽을 문장
"""


def N(i, text, bg=None, ov=None, tts=None, pause=0.0): return dict(id=i, kind='line', who='n', text=text, bg=bg, ov=ov, tts=tts, pause=pause)
def T(i, text, bg=None, ov=None, tts=None, pause=0.0): return dict(id=i, kind='line', who='t', text=text, bg=bg, ov=ov, tts=tts, pause=pause)
def Q(i, q, a, tts_q=None, tts_a=None, ox=False, img=None):
    return dict(id=i, kind='quiz', q=q, a=a, tts_q=tts_q, tts_a=tts_a, ox=ox, img=img)


